#!/usr/bin/env python3
"""Build a reproducible, still-gated NFL candidate runtime.

This does not authorize pricing or orders. It intersects a reviewed runtime
with exact Pinnacle selectors and independent score-grid payoff reviews, while
retaining an exclusion manifest and input hashes.
"""
import argparse
import copy
import hashlib
import json
from collections import Counter
from pathlib import Path


def sha256(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def build(runtime, review_rows, *, full_game_only=True, shadow_assume_usd_limits=False,
          risk_overrides=None):
    reviews = {row['market_key']: row['review'] for row in review_rows}
    selected, excluded = [], []
    for mapping in runtime['mappings']:
        key = mapping['market_key']
        review = reviews.get(key)
        reasons = []
        if review is None:
            reasons.append('payoff_review_missing')
        elif review.get('status') != 'completed_period_binary_verified':
            reasons.append('payoff_' + str(review.get('status')))
        if full_game_only and mapping.get('period', 'full_game') != 'full_game':
            reasons.append('period_outside_initial_scope')
        spec = mapping.get('pinnacle') or {}
        if not spec.get('selector_reference'):
            reasons.append('exact_pinnacle_selector_missing')
        if reasons:
            excluded.append({'market_key': key, 'kalshi_ticker': mapping.get('kalshi_ticker'),
                             'reasons': reasons})
            continue
        selected.append(copy.deepcopy(mapping))
    result = copy.deepcopy(runtime)
    result['mappings'] = selected
    result['mode'] = 'shadow'
    # Candidate runs should retain enough venue-level context to audit the
    # liquidity-weighted blend and later attribute markouts.
    result['record_venue_components'] = True
    result['launch_status'] = 'blocked_candidate; pricing_and_order_gates_unchanged'
    result['candidate_scope'] = {
        'full_game_only': full_game_only,
        'payoff_review': 'completed_period_binary_verified',
        'selector_review': 'exact_catalog_candidate',
        'orders_enabled': False,
    }
    if risk_overrides:
        allowed = {'per_contract_dollars', 'per_combo_dollars', 'per_fixture_dollars',
                   'maximum_committed_dollars'}
        if set(risk_overrides) - allowed:
            raise ValueError('unsupported_risk_override')
        for key, value in risk_overrides.items():
            if not isinstance(value, (int, float)) or value <= 0:
                raise ValueError('risk_override_must_be_positive')
            result[key] = value
        result['candidate_scope']['risk_overrides'] = dict(risk_overrides)
    if shadow_assume_usd_limits:
        for mapping in result['mappings']:
            spec = mapping.setdefault('pinnacle', {})
            spec['payoff_reference'] = mapping['mapping_reference'] + ':score_grid_v1'
            spec['limit_currency'] = 'USD'
            spec['limit_unit'] = 'stake'
            spec['limit_reference'] = 'shadow_assumption:numeric_oddspapi_limit_as_usd_stake'
            mapping.pop('pricing_block_reason', None)
        result['shadow_assumptions'] = {
            'numeric_oddspapi_limit_as_usd_stake': True,
            'orders_enabled': False,
            'promotion_blocker': 'provider_currency_and_unit_semantics_unverified',
        }
    result['comment'] = ('Narrow candidate generated by exact-selector and score-grid '
                         'intersection. Does not clear pricing blocks, approve '
                         'exception terms, validate stake limits, or enable orders.')
    return result, excluded


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--runtime', type=Path, required=True)
    parser.add_argument('--reviews', type=Path, required=True)
    parser.add_argument('--out', type=Path, required=True)
    parser.add_argument('--all-periods', action='store_true')
    parser.add_argument('--shadow-assume-usd-limits', action='store_true',
                        help='explicit research-only assumption; never enables orders')
    for name in ('per-contract-dollars', 'per-combo-dollars', 'per-fixture-dollars',
                 'maximum-committed-dollars'):
        parser.add_argument('--' + name, type=float, default=None)
    args = parser.parse_args()
    if args.out.exists():
        raise SystemExit(f'output_exists: {args.out}')
    runtime = json.loads(args.runtime.read_text())
    rows = json.loads(args.reviews.read_text())
    overrides = {}
    for cli, key in (('per_contract_dollars', 'per_contract_dollars'),
                     ('per_combo_dollars', 'per_combo_dollars'),
                     ('per_fixture_dollars', 'per_fixture_dollars'),
                     ('maximum_committed_dollars', 'maximum_committed_dollars')):
        value = getattr(args, cli)
        if value is not None:
            overrides[key] = value
    candidate, excluded = build(runtime, rows, full_game_only=not args.all_periods,
                                shadow_assume_usd_limits=args.shadow_assume_usd_limits,
                                risk_overrides=overrides or None)
    args.out.mkdir(parents=True)
    (args.out / 'runtime.json').write_text(json.dumps(candidate, indent=2) + '\n')
    (args.out / 'exclusions.json').write_text(json.dumps(excluded, indent=2) + '\n')
    summary = {
        'input_hashes': {str(args.runtime): sha256(args.runtime), str(args.reviews): sha256(args.reviews)},
        'candidate_mappings': len(candidate['mappings']),
        'excluded_mappings': len(excluded),
        'candidate_families': dict(Counter(m.get('period', 'full_game') + ':' + m['market_type']
                                           for m in candidate['mappings'])),
        'exclusion_reasons': dict(Counter(reason for row in excluded for reason in row['reasons'])),
        'pricing_authorized': False,
        'orders_enabled': False,
    }
    (args.out / 'summary.json').write_text(json.dumps(summary, indent=2) + '\n')
    print(json.dumps(summary, indent=2))


if __name__ == '__main__':
    main()
